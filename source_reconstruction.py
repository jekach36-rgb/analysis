"""
ВОССТАНОВЛЕНИЕ СИГНАЛА ПЕРВОИСТОЧНИКА
======================================
- Решение обратной задачи для оболочки PSP
- Восстановление сигнала главного квазара
- Оценка его мощности и частоты

Автор: Е.В. Чернокнижный
Версия: 1.0
"""

import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. ФИЗИЧЕСКИЕ КОНСТАНТЫ
# ============================================================

c = 3e8  # м/с
ly = 9.461e15  # м
G = 6.674e-11
M_sun = 1.989e30

# ============================================================
# 2. ПАРАМЕТРЫ МОДЕЛИ PSP
# ============================================================

R_shell_km = 1.5e23  # км
R_shell_m = R_shell_km * 1e3  # м

# Пики B-мод (наблюдаемые)
l_peaks = np.array([74, 109, 280])
M_phases = np.array([0.29, 0.35, 0.48])

# Ширина пиков (из таблицы)
delta_l = np.array([2, 3, 5])

# Частоты, соответствующие пикам (из данных квазаров)
f_obs = np.array([2.67e-9, 1.54e-8, 2.43e-9])  # Гц

# ============================================================
# 3. КОЭФФИЦИЕНТЫ ЗАТУХАНИЯ (из ширины пиков)
# ============================================================

print("="*60)
print("ВОССТАНОВЛЕНИЕ СИГНАЛА ПЕРВОИСТОЧНИКА")
print("="*60)

# Добротность Q = f / Δf
Q = f_obs / (f_obs * delta_l / l_peaks)
gamma = f_obs / Q  # коэффициент затухания

print(f"\n1️⃣ КОЭФФИЦИЕНТЫ ЗАТУХАНИЯ:")
for i, (l, q, g) in enumerate(zip(l_peaks, Q, gamma)):
    print(f"   Пик l={l}: Q={q:.0f}, gamma={g:.2e} 1/c")

# ============================================================
# 4. ВОССТАНОВЛЕНИЕ СИГНАЛА ИСТОЧНИКА
# ============================================================

print(f"\n2️⃣ ВОССТАНОВЛЕНИЕ СИГНАЛА ИСТОЧНИКА:")

# Время (логарифмическая шкала от 1 года до 1000 лет)
t_years = np.logspace(0, 3, 1000)
t_sec = t_years * 365.25 * 24 * 3600

# Наблюдаемый сигнал (затухающий синус)
A0 = 1.0  # амплитуда (нормирована)
f_source = f_obs[0]  # частота первого пика

S_obs = A0 * np.sin(2 * np.pi * f_source * t_sec) * np.exp(-gamma[0] * t_sec)

# Восстановленный сигнал (обратный ход)
S_source = S_obs * np.exp(+gamma[0] * t_sec)  # компенсация затухания

# ============================================================
# 5. ЧАСТОТА И МОЩНОСТЬ ИСТОЧНИКА
# ============================================================

print(f"\n3️⃣ ЧАСТОТА И МОЩНОСТЬ ИСТОЧНИКА:")

# Частота источника = частота наблюдаемого сигнала * e^(gamma * t)
f_source_corrected = f_obs[0] * np.exp(gamma[0] * np.mean(t_sec))
print(f"\n   Для пика l={l_peaks[0]}:")
print(f"      Наблюдаемая частота: {f_obs[0]:.2e} Гц")
print(f"      Скорректированная частота: {f_source_corrected:.2e} Гц")
print(f"      Истинный период источника: {1/f_source_corrected/(365.25*24*3600):.2e} лет")

# Оценка массы источника (из соотношения f ~ 1/M)
M_source = 1.0 / (f_source_corrected * G)  # приблизительно
M_source_Msun = M_source / M_sun
print(f"      Оценка массы источника: {M_source_Msun:.2e} M☉")

# Мощность источника (из амплитуды)
P_source = A0 * f_source_corrected * c**2 / G  # приблизительно
P_source_erg = P_source * 1e-7  # в эрг/с
print(f"      Оценка мощности источника: {P_source_erg:.2e} эрг/с")

# ============================================================
# 6. ГРАФИК
# ============================================================

print("\n📈 Построение графиков...")

fig, axes = plt.subplots(2, 2, figsize=(14, 10))

# 1. Наблюдаемый и восстановленный сигнал
ax1 = axes[0, 0]
ax1.plot(t_years, S_obs, 'b-', label='Наблюдаемый сигнал (затухающий)')
ax1.plot(t_years, S_source, 'r--', label='Восстановленный сигнал (без затухания)')
ax1.set_xlabel('Время (лет)')
ax1.set_ylabel('Амплитуда')
ax1.set_title('Восстановление сигнала источника')
ax1.legend()
ax1.grid(True, alpha=0.3)

# 2. Затухание
ax2 = axes[0, 1]
ax2.semilogy(t_years, np.exp(-gamma[0] * t_sec), 'g-', label='Затухание')
ax2.set_xlabel('Время (лет)')
ax2.set_ylabel('Амплитуда')
ax2.set_title(f'Затухание сигнала (gamma={gamma[0]:.2e} 1/c)')
ax2.legend()
ax2.grid(True, alpha=0.3)

# 3. Коэффициенты затухания
ax3 = axes[1, 0]
ax3.bar(l_peaks, gamma, color='coral')
ax3.set_xlabel('Мультиполь l')
ax3.set_ylabel('Коэффициент затухания γ (1/с)')
ax3.set_title('Затухание для разных пиков')
ax3.grid(True, alpha=0.3)

# 4. Масса источника
ax4 = axes[1, 1]
M_vals = [1.0 / (f_obs[i] * np.exp(gamma[i] * np.mean(t_sec))) / M_sun for i in range(len(l_peaks))]
ax4.bar(l_peaks, M_vals, color='purple')
ax4.set_xlabel('Мультиполь l')
ax4.set_ylabel('Масса источника (M☉)')
ax4.set_title('Оценка массы источника')
ax4.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('source_reconstruction.png', dpi=150)
print("✅ График сохранён как 'source_reconstruction.png'")

