import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. ФИЗИЧЕСКИЕ КОНСТАНТЫ И ПАРАМЕТРЫ
# ============================================================

c = 3e8  # м/с
G = 6.674e-11  # м³/(кг·с²)
M_sun = 1.989e30  # кг
ly = 9.461e15  # м

# Данные из наблюдений (пики B-мод)
l_peaks = np.array([74, 109, 280])
M_phases = np.array([0.29, 0.35, 0.48])

# Периоды квазаров (из данных)
periods_quasar = {
    'OJ 287': 11.86,   # лет
    '3C 273': [2.06, 13.03, 21.15]  # лет
}

# Параметры тора (из геометрии PSP)
alpha = 0.125
e0 = 0.12
M_obs = 0.29

# ============================================================
# 2. РАСЧЁТ СОБСТВЕННЫХ ЧАСТОТ ОБОЛОЧКИ
# ============================================================

# Предполагаем, что оболочка — это сфера радиуса R_shell
# Собственные частоты: f_n = c / (2 * R_shell) * n

def shell_frequencies(R_shell, n_max=10):
    """Собственные частоты оболочки"""
    f0 = c / (2 * R_shell)
    return np.array([f0 * n for n in range(1, n_max + 1)])

def period_from_frequency(f):
    """Период из частоты"""
    return 1.0 / f

# ============================================================
# 3. СВЯЗЬ ПИКОВ B-МОД С РЕЗОНАНСОМ
# ============================================================

print("="*60)
print("РАСЧЁТ РЕЗОНАНСА СИСТЕМЫ 'КВАЗАР-ОБОЛОЧКА'")
print("="*60)

# Оценка R_shell из калибровки PSP
R_shell_0 = 1.5e23  # км (из калибровки)
R_shell_m = R_shell_0 * 1e3  # метры

print(f"\n1️⃣ РАЗМЕР ОБОЛОЧКИ (из калибровки):")
print(f"   R_shell = {R_shell_0:.2e} км = {R_shell_0/ly:.2e} св. лет")

# Собственные частоты оболочки
n_max = 10
f_shell = shell_frequencies(R_shell_m, n_max)
T_shell = period_from_frequency(f_shell) / (365.25 * 24 * 3600)  # в годах

print(f"\n2️⃣ СОБСТВЕННЫЕ ЧАСТОТЫ ОБОЛОЧКИ:")
print(f"   n\tf (Гц)\t\tT (лет)")
for i, (f, T) in enumerate(zip(f_shell, T_shell), 1):
    print(f"   {i}\t{f:.2e}\t{T:.2f}")

# ============================================================
# 4. РЕЗОНАНС С ПЕРИОДАМИ КВАЗАРОВ
# ============================================================

print(f"\n3️⃣ РЕЗОНАНС С ПЕРИОДАМИ КВАЗАРОВ:")

# Основной период OJ 287
T_OJ = periods_quasar['OJ 287']
f_OJ = 1.0 / (T_OJ * 365.25 * 24 * 3600)

print(f"\n   OJ 287:")
print(f"      T = {T_OJ:.2f} лет")
print(f"      f = {f_OJ:.2e} Гц")

# Находим ближайшую гармонику оболочки
n_OJ = np.argmin(np.abs(f_shell - f_OJ)) + 1
print(f"      Ближайшая гармоника оболочки: n = {n_OJ}")
print(f"      f_shell[{n_OJ}] = {f_shell[n_OJ-1]:.2e} Гц")
print(f"      Отклонение: {(f_shell[n_OJ-1] - f_OJ)/f_OJ*100:.2f}%")

# Периоды 3C 273
for T in periods_quasar['3C 273']:
    f = 1.0 / (T * 365.25 * 24 * 3600)
    n = np.argmin(np.abs(f_shell - f)) + 1
    print(f"\n   3C 273 (T={T:.2f} лет):")
    print(f"      f = {f:.2e} Гц")
    print(f"      Ближайшая гармоника оболочки: n = {n}")
    print(f"      Отклонение: {(f_shell[n-1] - f)/f*100:.2f}%")

# ============================================================
# 5. ЗАТУХАНИЕ РЕЗОНАНСА
# ============================================================

# Оценка затухания из ширины пиков
# Δl ~ 5 (из таблицы) → Δf = f * (Δl / l)

print(f"\n4️⃣ ЗАТУХАНИЕ РЕЗОНАНСА:")

for l, T in zip(l_peaks, [11.86, 2.06, 13.03]):
    f = 1.0 / (T * 365.25 * 24 * 3600)
    delta_l = 5  # ширина пика (из таблицы)
    delta_f = f * (delta_l / l)
    Q = f / delta_f  # добротность резонатора
    gamma = f / Q  # коэффициент затухания
    
    print(f"\n   Пик l = {l} (T = {T:.2f} лет):")
    print(f"      f = {f:.2e} Гц")
    print(f"      Δf = {delta_f:.2e} Гц")
    print(f"      Добротность Q = {Q:.0f}")
    print(f"      Коэффициент затухания γ = {gamma:.2e} 1/c")
    print(f"      Время затухания τ = 1/γ = {1/gamma:.2e} с = {1/gamma/(365.25*24*3600):.2f} лет")

# ============================================================
# 6. ВЫВОД РАЗМЕРА ОБОЛОЧКИ ИЗ РЕЗОНАНСА
# ============================================================

print(f"\n5️⃣ РАЗМЕР ОБОЛОЧКИ ИЗ РЕЗОНАНСА:")

# Из резонанса с OJ 287
R_shell_res = c / (2 * f_OJ * n_OJ)
print(f"\n   Из резонанса с OJ 287 (n = {n_OJ}):")
print(f"      R_shell = {R_shell_res:.2e} м = {R_shell_res/1e3:.2e} км")
print(f"      Отклонение от калибровки: {(R_shell_res/R_shell_m - 1)*100:.2f}%")

# Из резонанса с 3C 273 (период 2.06 лет)
f = 1.0 / (2.06 * 365.25 * 24 * 3600)
n = np.argmin(np.abs(f_shell - f)) + 1
R_shell_res_2 = c / (2 * f * n)
print(f"\n   Из резонанса с 3C 273 (T=2.06 лет, n={n}):")
print(f"      R_shell = {R_shell_res_2:.2e} м = {R_shell_res_2/1e3:.2e} км")
print(f"      Отклонение от калибровки: {(R_shell_res_2/R_shell_m - 1)*100:.2f}%")

# ============================================================
# 7. ГРАФИК
# ============================================================

print("\n📈 Построение графиков...")

fig, axes = plt.subplots(2, 2, figsize=(14, 10))

# 1. Спектр собственных частот оболочки
ax1 = axes[0, 0]
n_vals = np.arange(1, n_max + 1)
ax1.scatter(n_vals, T_shell, color='blue', label='Собственные частоты оболочки')
ax1.axhline(y=T_OJ, color='red', linestyle='--', label=f'OJ 287 (T={T_OJ:.2f} лет)')
for T in periods_quasar['3C 273']:
    ax1.axhline(y=T, color='green', linestyle=':', label=f'3C 273 (T={T:.2f} лет)')
ax1.set_xlabel('Номер гармоники n')
ax1.set_ylabel('Период (лет)')
ax1.set_title('Собственные частоты оболочки и периоды квазаров')
ax1.legend()
ax1.grid(True, alpha=0.3)

# 2. Добротность резонатора
ax2 = axes[0, 1]
Q_vals = [f_shell[np.argmin(np.abs(f_shell - 1.0/(T*365.25*24*3600)))] / (f_shell[np.argmin(np.abs(f_shell - 1.0/(T*365.25*24*3600)))] * 5 / l) for T, l in zip([11.86, 2.06, 13.03], l_peaks)]
ax2.bar(['l=74', 'l=109', 'l=280'], Q_vals, color='coral')
ax2.set_ylabel('Добротность Q')
ax2.set_title('Добротность резонатора (Q = f/Δf)')
ax2.grid(True, alpha=0.3)

# 3. Размер оболочки
ax3 = axes[1, 0]
R_shell_vals = [R_shell_res/1e3, R_shell_res_2/1e3, R_shell_0]
ax3.bar(['Из OJ 287', 'Из 3C 273', 'Из калибровки'], R_shell_vals, color=['blue', 'green', 'orange'])
ax3.set_ylabel('Радиус оболочки (10²⁰ км)')
ax3.set_title('Сравнение размеров оболочки')
ax3.grid(True, alpha=0.3)

# 4. Затухание
ax4 = axes[1, 1]
tau_vals = [1/gamma for gamma in [f_shell[np.argmin(np.abs(f_shell - 1.0/(T*365.25*24*3600)))] / (f_shell[np.argmin(np.abs(f_shell - 1.0/(T*365.25*24*3600)))] * 5 / l) for T, l in zip([11.86, 2.06, 13.03], l_peaks)]]
tau_years = [tau/(365.25*24*3600) for tau in tau_vals]
ax4.bar(['l=74', 'l=109', 'l=280'], tau_years, color='purple')
ax4.set_ylabel('Время затухания (лет)')
ax4.set_title('Время затухания резонанса')
ax4.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('resonance_analysis.png', dpi=150)
print("✅ График сохранён как 'resonance_analysis.png'")

