data = []
lines = raw_data.strip().split('\n')

for line in lines:
    parts = line.split('|')
    if len(parts) < 3:
        continue
    
    # ID
    obj_id = parts[0].strip()
    
    # Все числа в строке
    numbers = []
    for part in parts[1:]:
        for token in part.split():
            try:
                val = float(token)
                numbers.append(val)
            except:
                pass
    
    # Периоды — числа между 100 и 5000
    periods = [n for n in numbers if 100 < n < 5000]
    
    # Kmag — число между 6 и 10
    kmag = np.nan
    for n in numbers:
        if 6 < n < 10:
            kmag = n
            break
    
    if periods:
        data.append({
            'id': obj_id,
            'periods': periods,
            'kmag': kmag
        })

